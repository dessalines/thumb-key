/*
 * The generateEmojiSearchData task: regenerates app/src/main/assets/emoji_search.tsv, the
 * emoji keyboard's search index. Run it by hand when the emoji data should be refreshed:
 *
 *     ./gradlew generateEmojiSearchData
 *
 * Each line is: emoji <TAB> name <TAB> space-separated keywords. Emoji come in the order of
 * Unicode's emoji-test.txt, without skin-tone variants or components, and the keywords are
 * CLDR's English annotations.
 */

import groovy.json.JsonSlurper
import java.net.URI

abstract class GenerateEmojiSearchData : DefaultTask() {
    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    private val emojiTestUrl =
        "https://raw.githubusercontent.com/unicode-org/cldr/main/tools/cldr-code/" +
            "src/main/resources/org/unicode/cldr/util/data/emoji/emoji-test.txt"
    private val cldrJson = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/"
    private val annotationUrls =
        listOf(
            cldrJson + "cldr-annotations-full/annotations/en/annotations.json",
            cldrJson + "cldr-annotations-derived-full/annotationsDerived/en/annotations.json",
        )
    private val skinTones = setOf(0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF)
    private val variationSelector16 = "️"

    // A word of an emoji's name: letters, digits, underscores, apostrophes and hyphens
    private val nameWordRegex = Regex("(?U)[\\w’'-]+")

    private fun fetch(url: String): String = URI(url).toURL().readText(Charsets.UTF_8)

    /** CLDR's English keywords for each emoji. The first file to list an emoji wins. */
    @Suppress("UNCHECKED_CAST")
    private fun loadAnnotations(): Map<String, List<String>> {
        val keywordsByEmoji = mutableMapOf<String, List<String>>()
        for (url in annotationUrls) {
            val data = JsonSlurper().parseText(fetch(url)) as Map<String, Any>
            val root = (data["annotations"] ?: data["annotationsDerived"]) as Map<String, Any>
            val annotations = root["annotations"] as Map<String, Map<String, Any>>
            for ((emoji, annotation) in annotations) {
                val keywords = (annotation["default"] as List<String>?).orEmpty()
                keywordsByEmoji.putIfAbsent(emoji, keywords)
            }
        }
        return keywordsByEmoji
    }

    @TaskAction
    fun generate() {
        val keywordsByEmoji = loadAnnotations()
        val lines =
            mutableListOf(
                "# Emoji search index, generated by ./gradlew generateEmojiSearchData",
                "# from Unicode emoji-test.txt and CLDR annotations.",
                "# Unicode data: Copyright (c) Unicode, Inc. https://www.unicode.org/license.txt",
            )
        var group = ""
        for (line in fetch(emojiTestUrl).lines()) {
            if (line.startsWith("# group:")) {
                group = line.substringAfter(":").trim()
                continue
            }
            if (line.isEmpty() || line.startsWith("#") || group == "Component") continue

            val (codes, rest) = line.split(";", limit = 2)
            val (status, comment) = rest.split("#", limit = 2)
            if (status.trim() != "fully-qualified") continue

            val codePoints = codes.trim().split(Regex("\\s+")).map { it.toInt(16) }
            if (codePoints.any { it in skinTones }) continue
            val emoji = buildString { codePoints.forEach { appendCodePoint(it) } }

            // The comment is "<emoji> E<version> <name>"
            val name = comment.trim().split(" ", limit = 3)[2]
            val keywords =
                keywordsByEmoji[emoji]?.takeIf { it.isNotEmpty() }
                    ?: keywordsByEmoji[emoji.replace(variationSelector16, "")].orEmpty()

            // Keywords that only repeat a word of the name add nothing to the search
            val lowercaseName = name.lowercase()
            val nameWords = nameWordRegex.findAll(lowercaseName).map { it.value }.toSet()
            val extraKeywords =
                keywords
                    .map { it.lowercase() }
                    .filter { it !in nameWords && it != lowercaseName }
                    .distinct()
            lines.add("$emoji\t$name\t${extraKeywords.joinToString(" ")}")
        }
        val file = outputFile.get().asFile
        file.parentFile.mkdirs()
        file.writeText(lines.joinToString("\n") + "\n", Charsets.UTF_8)
        logger.lifecycle("Wrote ${lines.size - 3} emoji to $file")
    }
}

tasks.register<GenerateEmojiSearchData>("generateEmojiSearchData") {
    group = "generation"
    description = "Regenerates the emoji search index from Unicode and CLDR data."
    outputFile.set(rootProject.layout.projectDirectory.file("app/src/main/assets/emoji_search.tsv"))
    // It downloads the latest data, so it's never up to date
    outputs.upToDateWhen { false }
}
