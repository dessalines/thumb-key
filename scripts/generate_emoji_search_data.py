#!/usr/bin/env python3
"""
Generates app/src/main/assets/emoji_search.tsv, the emoji keyboard's search index.

Each line is: emoji <TAB> name <TAB> space-separated keywords. Emoji come in the
order of Unicode's emoji-test.txt, without skin-tone variants or components, and
the keywords are CLDR's English annotations.

Usage, from the repository root:
    python3 scripts/generate_emoji_search_data.py
"""

import json
import re
import pathlib
import urllib.request

EMOJI_TEST_URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr/main/tools/cldr-code/"
    "src/main/resources/org/unicode/cldr/util/data/emoji/emoji-test.txt"
)
CLDR_JSON = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/"
ANNOTATION_URLS = [
    CLDR_JSON + "cldr-annotations-full/annotations/en/annotations.json",
    CLDR_JSON + "cldr-annotations-derived-full/annotationsDerived/en/annotations.json",
]
OUTPUT = pathlib.Path("app/src/main/assets/emoji_search.tsv")

SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
VARIATION_SELECTOR_16 = "️"


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def load_annotations() -> dict[str, list[str]]:
    keywords_by_emoji: dict[str, list[str]] = {}
    for url in ANNOTATION_URLS:
        data = json.loads(fetch(url))
        root = data.get("annotations") or data.get("annotationsDerived")
        for emoji, annotation in root["annotations"].items():
            keywords_by_emoji.setdefault(emoji, annotation.get("default", []))
    return keywords_by_emoji


def main() -> None:
    keywords_by_emoji = load_annotations()
    lines = [
        "# Emoji search index, generated by scripts/generate_emoji_search_data.py",
        "# from Unicode emoji-test.txt and CLDR annotations.",
        "# Unicode data: Copyright (c) Unicode, Inc. https://www.unicode.org/license.txt",
    ]
    group = ""
    for line in fetch(EMOJI_TEST_URL).splitlines():
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if not line or line.startswith("#") or group == "Component":
            continue
        codes, rest = line.split(";", 1)
        status, comment = rest.split("#", 1)
        if status.strip() != "fully-qualified":
            continue
        code_points = [int(code, 16) for code in codes.split()]
        if SKIN_TONES.intersection(code_points):
            continue
        emoji = "".join(chr(code_point) for code_point in code_points)
        # The comment is "<emoji> E<version> <name>"
        name = comment.strip().split(" ", 2)[2]
        keywords = keywords_by_emoji.get(emoji) or keywords_by_emoji.get(
            emoji.replace(VARIATION_SELECTOR_16, ""), []
        )
        name_words = set(re.findall(r"[\w’'-]+", name.lower()))
        extra_keywords = []
        for keyword in keywords:
            keyword = keyword.lower()
            if keyword not in name_words and keyword != name.lower() and keyword not in extra_keywords:
                extra_keywords.append(keyword)
        lines.append(f"{emoji}\t{name}\t{' '.join(extra_keywords)}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines) - 3} emoji to {OUTPUT}")


if __name__ == "__main__":
    main()
